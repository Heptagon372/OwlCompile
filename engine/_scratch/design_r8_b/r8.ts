// 새 요소: 고리를 도는 고양이(loop). 2×2 고리를 도는 고양이가 지키는 길목을 나갈 때·돌아올 때 두 번 지난다.
// 두 번의 시각이 달라서 잠자기 하나를 **반복 몸통 안에** 두어야 한다 — 맨 앞에 두면 돌아오는 길에 죽는다.
// R7의 한 걸음(좌회전판)을 그대로 쓴다: 만약 앞이 벽이면 { 좌회전 } 아니면 { 만약 앞이 구덩이면 { 점프 } 아니면 { 앞으로 } }.
//
//        x: 01234567
//   y0:     ########
//   y1:     #S######     S(1,1) 남쪽을 봄
//   y2:     #O######     구덩이 (1,2)
//   y3:     #.##K###     열쇠 (4,3) — 막다른 곳(고리 위쪽)
//   y4:     #.##.###
//   y5:     #O##O###     구덩이 (1,5), (4,5) — 고리로 드나드는 길은 전부 점프
//   y6:     #MOcc###     쥐 (1,6), 구덩이 (2,6), 고양이 고리 A(3,6) B(4,6)
//   y7:     ###ccMDG     고리 D(3,7) C(4,7), 쥐 (5,7), 문 (6,7), 둥지 G(7,7)
//
// 고양이: path A(3,6) → B(4,6) → C(4,7) → D(3,7) → A …, loop, 주기 4. 틱 t 끝의 고양이 = path[t mod 4]
//   (t≡0 A, t≡1 B, t≡2 C, t≡3 D). 고리의 바깥 이웃은 구덩이 (2,6)·(4,5)와 (5,7)뿐 — 고리로 들어가는 길은 점프뿐이고
//   (구덩이 앞이 아니면 점프 착지가 벽·구덩이라 점프로 홀짝을 바꿀 수 없다), 걸어 나가는 길은 C→(5,7) 하나다.
// 둥지 {(7,7)}은 문 (6,7)과 벽으로만 둘러싸여 있어 열쇠 (4,3) 없이는 못 들어간다 → 고리를 두 번 지나야 한다.
//
// 의도한 경로 (20틱) = 반복 2 { 잠자기 / 반복 9 { 한 걸음 } }
//   t1  잠자기                          (고양이 A→B)
//   t2  점프 (1,2) 넘어 (1,3)           t3  (1,4)                 t4  점프 (1,5) 넘어 (1,6) 쥐
//   t5  좌회전(동) [(1,7) 벽]           (고양이 4틱 끝 A, 5틱 끝 B)
//   t6  점프 (2,6) 넘어 A(3,6)          ← 나가는 길목: 6틱 끝 고양이 C, A·B에 없다
//   t7  B(4,6)                          (고양이 C→D)
//   t8  좌회전(북) [(5,6) 벽]           (고양이 D→A) — B에 2틱 머무는 동안 고양이는 C·D·A
//   t9  점프 (4,5) 넘어 (4,4)           t10 (4,3) 열쇠 — 첫 반복 9가 여기서 끝난다
//   t11 잠자기                          ← 둘째 잠자기: 고리로 돌아가는 시각을 1틱 늦춘다
//   t12 좌회전(서) [(4,2) 벽]           t13 좌회전(남) [(3,3) 벽]        t14 (4,4)
//   t15 점프 (4,5) 넘어 B(4,6)          ← 돌아오는 길목: 14틱 끝 고양이 C, 15틱 끝 D
//   t16 C(4,7)                          (고양이 D→A)
//   t17 좌회전(동) [(4,8) 맵 밖]        (고양이 A→B)
//   t18 (5,7) 쥐                        t19 문 (6,7) 열쇠로 연다        t20 (7,7) 둥지
//
// 시각 규칙: 고리 두 칸을 "들어가기·한 칸 더·회전"으로 3틱 지나는 동안 고양이가 그 두 칸에 오면 안 된다.
//   나가는 길 A→B: A에 들어가는 틱 k ≡ 2 (mod 4)뿐 (k=6). 돌아오는 길 B→C: B에 들어가는 틱 k ≡ 3뿐 (k=15).
//   잠자기 없이 A에 닿는 틱은 늘 홀수(가장 빨라야 5, 그 뒤 7·9 …): 1열에서는 남→동으로 도는 회전 수가 홀수, 되돌아갔다 오는
//   걸음 수가 짝수이고 점프는 구덩이 앞에서만 되므로(다른 점프는 벽·구덩이 착지) 홀짝을 바꿀 수 없다 → 잠자기 없이는 어떤
//   액션 열로도 못 나간다(BFS). 잠자기 1개를 앞에 두면
//   6틱(≡2)에 나가지만 왕복이 8틱이라 14틱(≡2)에 B로 되돌아와 고양이를 밟는다. 앞에 2개면 7틱(≡3)에 A → 9틱에 B에서
//   잡힌다. 잠자기 1개 + 열쇠 쪽에서 잠자기 1개 = 15틱(≡3)만 산다 → 반복 몸통 안의 잠자기.
//   같은 이유로 "잠자기 r개 뒤에 잠자기 없음"(r=0~3, 고양이 출발 칸을 r칸 돌린 BFS)도 전부 불가 — 잠자기는 길 중간에 있어야 한다.
//
// 함정: 잠자기 없음 → 5틱째 A(3,6)에서 "고양이를 밟았다". 잠자기를 맨 앞에 → 14틱째 B(4,6)에서 "고양이를 밟았다".
//   반복 몸통 끝에 잠자기(반복 2 { 반복 9 { 한 걸음 } / 잠자기 }) → 5틱째 A. 잠자기 2개를 앞에 → 9틱째 B에서 "고양이에게 잡혔다".
//   반복 8이면 둘째 묶음이 (5,7)에서 끝나 미도착(stuck, 70점) — 두 묶음 모두 정확히 9걸음.
//
// ⚠ 알려진 한계: 상한 9에서는 함수 형태가 들어가지 않는다 — 함수 F { 잠자기 / 반복 9 { 한 걸음 } } / F 호출 / F 호출 = 10블록.
//   대표 정답은 함수 없는 8블록(145점)이고, 함수를 써도 상한 안에서 145점을 넘는 프로그램은 없다(빠짐없는 탐색).
