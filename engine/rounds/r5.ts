//   y2:     #.#.M.#.
//   y3:     #.#.#.#.
//   y4:     #.#.cccc     고양이 골목 (4,4)→(7,4), 교차점 (7,4)
//   y5:     #.#.#G#c     둥지 G(5,5): 골목 칸 (5,4)로만 들어갈 수 있다
//   y6:     #S#..O.c     구덩이 (5,6)
//   y7:     ########
//
// 고양이: path (4,4)(5,4)(6,4)(7,4)(7,5)(7,6), pingpong, 주기 10틱.
//   c 칸이 가지 없는 한 줄이고 (4,4)가 끝이라 움직임이 하나로 정해진다.
//   골목 동쪽으로 → 교차점 → 오른쪽 열을 내려가 모퉁이 (7,6) → 되돌아 골목 끝 (4,4).
//   교차점 (7,4)에 있는 틱: 3, 7, 13, 17, 23, 27, 33 …
//
// 의도한 경로 (잠자기 1 + 36틱 = 37틱, 시계 방향 나선):
//   t1        잠자기
//   t2-7      북진 (1,5)…(1,0)            t8 우회전(동)   [(1,-1) 맵 밖]
//   t9-14     동진 (2,0)…(7,0), 쥐(4,0) t11  t15 우회전(남)  [(8,0) 맵 밖]
//   t16-21    남진 (7,1)…(7,6), 교차점 (7,4) t19   t22 우회전(서)  [(7,7) 벽]
//   t23       (6,6)   t24 점프 → (4,6) [구덩이 (5,6)]   t25 (3,6)   t26 우회전(북) [(2,6) 벽]
//   t27-30    북진 (3,5)…(3,2)            t31 우회전(동)  [(3,1) 벽]
//   t32-33    동진 (4,2)쥐, (5,2)          t34 우회전(남)  [(6,2) 벽]
//   t35-37    남진 (5,3), (5,4) 골목, (5,5) 둥지
//
// 잠자기가 없으면 모든 칸이 1틱 빨라진다: 17틱에 (7,3), 그 틱 끝에 고양이가 (7,5)→(7,4).
// 18틱에 부엉이가 먼저 움직여 (7,4)로 들어가고 고양이는 아직 거기 있다 → "고양이를 밟았다".
// 잠자기 1개면 19틱에 (7,4) — 고양이는 18틱에 이미 (6,4)로 떠났고 19틱에 (5,4)로 더 멀어진다.
// 이후 부엉이가 (7,6)을 떠나는 23틱 뒤 25틱에야 고양이가 모퉁이에 닿고, 둘째 교차 (5,4)는
// 36틱(고양이는 (7,6)→(7,5))이라 안전하다.
// (7,4)는 병목이다: 시작 구역(1열·윗줄·7열 위쪽)에서 나머지로 가려면 (7,4)를 밟거나
// (7,3)에서 뛰어넘어야 한다. 센서 반복은 구덩이 앞에서만 점프하므로 교차점을 걸어서 지난다.
