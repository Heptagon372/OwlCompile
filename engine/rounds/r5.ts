// 새 요소: 움직이는 고양이·잠자기. R3(만약 앞이 벽이면)과 R4(만약 앞이 구덩이면)를 합친 뒤 틱을 센다.
//
//        x: 01234567
//   y0:     #...M...     S(1,6) 북쪽을 봄. 윗줄(y=0)과 오른쪽 열(x=7)은 판 가장자리 = 맵 밖이 벽
