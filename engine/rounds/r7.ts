//
// 한 걸음 = 만약 앞이 벽이면 { 좌회전 } 아니면 { 만약 앞이 구덩이면 { 점프 } 아니면 { 앞으로 } }   (R5의 한 걸음, 좌회전판)
// 의도한 경로 (16틱): F = 반복 9 { 한 걸음 }
//   F 1회차 (9틱)
//     t1  점프 (3,2) 넘어 (3,3)      t2  점프 (3,4) 넘어 (3,5)      t3  좌회전(동) [(3,6) 벽]
//     t4  (4,5) 열쇠                 t5  좌회전(북) [(5,5) 벽]      t6  (4,4)
//     t7  좌회전(서) [(4,3) 벽]      t8  점프 (3,4) 넘어 (2,4)      t9  좌회전(남) [(1,4) 벽]
//   t10 잠자기                        ← 고양이가 10틱 끝에 (2,7)로 온다
//   F 2회차
//     t11 점프 (2,5) 넘어 (2,6) 쥐   (고양이 (2,7)→(1,7))
//     t12 (2,7) 골목 끝              (고양이 (1,7)→(0,7))
//     t13 좌회전(동) [(2,8) 맵 밖]   t14 (3,7) 쥐 (고양이가 방금 떠난 칸 (2,7)로 돌아온다)
//     t15 점프 (4,7) 넘어 문 (5,7) — 열쇠로 연다     t16 (6,7) 둥지
//
// 잠자기가 없으면 모든 칸이 1틱 빨라져 11틱째 부엉이가 (2,7)로 들어가는데 고양이는 10틱 끝에 이미 거기 와 있다
// → "고양이를 밟았다". 잠자기 없이는 어떤 액션 열로도 둥지에 못 간다(블록 수 무관, verify-search의 상태 BFS):
// 걷기·점프·회전만으로는 (2,7)을 안전하게 지나는 시각을 맞출 수 없다(제자리 회전으로 방향을 되찾으면 늘 짝수 틱이 든다).
// 조건 블록 없이는(함수를 써도) 상한 10 안에서 대표 정답 점수(140)에 못 미친다(빠짐없는 탐색).
//
