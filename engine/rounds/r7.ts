//   y5:     ##O.K###     구덩이 (2,5), 열쇠 (4,5)
//   y6:     ##M#####     쥐 (2,6)
//   y7:     cccMODG#     고양이 골목 (0,7)~(2,7), 쥐 (3,7), 구덩이 (4,7), 문 (5,7), 둥지 G(6,7)
//
// 고양이: path (0,7)(1,7)(2,7), pingpong, 주기 4. (2,7)에 있는 틱: 2, 6, 10, 14 …  (1,7)은 홀수 틱.
