/** 한 걸음: 벽이면 좌회전, 아니면 (구덩이면 점프, 아니면 앞으로). 언제나 1틱. */
const step = (): Block => ({
  id: 'if_wall',
  then: [{ id: 'left' }],
  else: [{ id: 'if_pit', then: [{ id: 'jump' }], else: [{ id: 'forward' }] }],
});

/** 반복 9 { 한 걸음 } — 딱 9걸음. 6블록. */
const walk9 = (): Block => ({ id: 'repeat', n: 9, body: [step()] });

