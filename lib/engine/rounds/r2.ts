//       오른변을 "점프 점프"로 건너면 (6,5) 쥐를 뛰어넘어 못 먹는다(9블록까지 줄지만 135점 < 150점).
//
// ⚠ 알려진 한계 (리뷰 확인, 스펙 §8 R2 위반 — 설계 결정 대기):
//   센서(만약 앞이 구덩이면)를 쓰면 def 없이 7블록으로 같은 13틱·쥐 2마리 경로를 낸다(165점 > 대표 정답 150점).
//   예) 반복 5 { 앞으로 / 만약 앞이 구덩이면 { 점프 좌회전 } / 만약 앞이 구덩이면 { 점프 } }
//       반복 6 { 만약 앞이 구덩이면 { 점프 } 아니면 { 앞으로 / 만약 앞이 구덩이면 { 점프 좌회전 } } }
//   이 맵에서는 모든 점프가 구덩이 위이고 "앞으로 뒤 구덩이 = 모퉁이"라 구덩이 센서 하나로 모퉁이가 보인다.
//   빠짐없는 탐색(함수 동치 제거)으로 확인한 것: def 없는 쥐 2마리 최소 = 7블록, def를 쓴 프로그램은 6블록 이하 없음.
//   따라서 대표 정답은 "센서 없이" 최선일 뿐이다. 모퉁이 모티프를 유지하는 맵 수정(점프 칸 구덩이/바닥, 모퉁이 앞
