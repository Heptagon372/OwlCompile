//   +   점프(4,2)                 [구덩이 (5,2)] … 윗변은 구덩이로 시작한다
//   F   앞으로(3,2) 쥐 · 점프(1,2) [구덩이 (2,2)] · 좌회전(S)
//   F   앞으로(1,3) · 점프(1,5) 둥지 [구덩이 (1,4)]  (마지막 좌회전은 둥지 도착으로 실행 안 됨)
// 모퉁이 모티프 F = 앞으로·점프·좌회전 이 네 번 나오는데, 그 사이에 끼는 동작이
