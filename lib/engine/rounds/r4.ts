// 문을 열지 않고는 들어갈 수 없다(문 위는 열쇠가 있어도 뛰어넘지 못한다).
// (4,5)를 벽으로 막은 이유: 열려 있으면 4열로 곧장 내려가는 안뜰 지름길
// "앞으로 / 반복 2 { 점프 우회전 앞으로 점프 }"(6블록, if_pit 없음, 쥐 2, 160점)이
// 대표 정답(140점)을 이겨 버린다. 막은 뒤에는 그 프로그램이 6틱째 벽에 막힌다.
//
// 의도한 경로 (11틱, 둘레 ㄷ자):
//   1행 동진  (1,1)→앞으로(2,1)→점프(4,1)열쇠→점프(6,1)       [구덩이 (3,1),(5,1)]
//   우회전 → 6열 남진  점프(6,3)→앞으로(6,4)→점프(6,6)         [구덩이 (6,2),(6,5)]
//   우회전 → 6행 서진  점프(4,6)쥐→앞으로(3,6)문 열림→점프(1,6)둥지 [구덩이 (5,6),(2,6)]
// 세 변 모두 "3회 반복"이고 구덩이 위치가 매번 달라, 루프 본문 하나
