//   y5:     ######O#       되돌아 (5,4)(6,4)로 둘러 가야 한다 → 쥐 2마리 경로는 14틱·13블록 이상(상한 초과)
//   y6:     #GODMO.#     아랫줄: 둥지(1,6)·구덩이·문(3,6)·쥐(4,6)·구덩이·바닥
//   y7:     ########
//
